"""Lock on development only, then consume the reserved historical block once.

No production promotion. The historical confirmation is not a prospective trial.
Local joblib files must be generated by this script, not downloaded from others.
"""
import argparse, hashlib, json, os, sys
from datetime import datetime, timezone
from pathlib import Path
os.environ.setdefault('OMP_NUM_THREADS','1')
os.environ.setdefault('OPENBLAS_NUM_THREADS','1')
import joblib
import pandas as pd
sys.path.insert(0,str(Path(__file__).resolve().parents[1]/'model'))
import research_goal_temporal as r
from henachel.features import build_feature_frame
from henachel.data import validate_player_games,final_mask
from henachel.goal import augment_goal_features,goal_labels,numeric_features,GOAL_PARAMS
from henachel.goal_experiment import paired_comparison
from henachel.manifest import manifest


CLOSURE_REPORT=Path(__file__).resolve().parents[1]/'docs/research_20261005/final_result.json'

def ensure_not_closed():
    if CLOSURE_REPORT.exists():raise ValueError('Study 201e6ff closed; reserved block permanently consumed')

def sha(path):return hashlib.sha256(Path(path).read_bytes()).hexdigest()
def save(path,data):
    with Path(path).open('x') as f:json.dump(data,f,indent=2,default=str,allow_nan=False)

def choose(report):
    if report['holdout_used'] or report['protocol']!=r.frozen_protocol():raise ValueError('Development protocol mismatch')
    eligible=[name for name in r.FAMILIES if report['comparisons'][name]['development_only_selected']]
    # Only eligible families; no combinations. Logloss is the primary metric.
    return min(eligible,key=lambda n:(report['reports'][n]['metrics']['logloss'],n)) if eligible else 'baseline'

def lock(features,development,output):
    ensure_not_closed()
    if output.exists():raise FileExistsError('Candidate lock directory exists')
    report=json.loads((development/'summary.json').read_text());name=choose(report)
    source_report=json.loads(features.with_suffix('.report.json').read_text())
    if source_report['holdout_used']:raise ValueError('Source features consumed reserved block')
    if sha(features)!=report['source_sha256'] or sha(r.PROTOCOL_PATH)!=report['protocol_sha256'] or sha(Path(r.__file__))!=report['runner_sha256']:
        raise ValueError('Development inputs/code changed')
    frame=r.development_only(pd.read_csv(features,low_memory=False))
    frame=r.augment_research_features(augment_goal_features(frame));frame['a_marque_un_but']=goal_labels(frame)
    output.mkdir(parents=True)
    models={};meta={};cut=r.PROTOCOL['development_end']
    for variant in dict.fromkeys(['baseline',name]):
        cols=r.BASELINE+r.FAMILIES.get(variant,[])
        model,cal,info=r.fit(frame,cut,cols)
        models[variant]=(model,cal,info);meta[variant]=dict(features=cols,parameters=GOAL_PARAMS,fit=info)
    bundle=output/'locked_models.joblib';joblib.dump(models,bundle,compress=3)
    metadata=dict(candidate=name,models=meta,training_prevalence=float(frame.a_marque_un_but.mean()),seed=42,
        protocol=r.frozen_protocol(),protocol_sha256=sha(r.PROTOCOL_PATH),source_features_sha256=sha(features),
        source_raw_sha256=source_report['source_sha256'],
        development_summary_sha256=sha(development/'summary.json'),model_sha256=sha(bundle),
        baseline_development=report['reports']['baseline'],candidate_development=report['reports'][name],
        selection='Preregistered eligibility; lowest development logloss among eligible, lexical tie; no combinations',
        holdout_labels_used=False,locked_at=datetime.now(timezone.utc).isoformat(),
        manifest=manifest([features,development/'summary.json',Path(__file__),Path(r.__file__)],GOAL_PARAMS))
    save(output/'candidate_locked.json',metadata);print(json.dumps({'candidate':name,'holdout_used':False,'calibration':{n:m['fit']['calibration']['method'] for n,m in meta.items()}},indent=2))
    return metadata

def reserve_once(output):
    # Refuse before reading holdout input if a previous evaluation began.
    save(output/'HOLDOUT_OPENED.json',{'opened_at':datetime.now(timezone.utc).isoformat(),'retry_policy':'No new tuning or automatic rerun; preserve any partial outputs.'})

def evaluate(source,output):
    ensure_not_closed()
    locked=json.loads((output/'candidate_locked.json').read_text())
    if locked['protocol']!=r.frozen_protocol() or locked['protocol_sha256']!=sha(r.PROTOCOL_PATH):raise ValueError('Changed protocol')
    if sha(output/'locked_models.joblib')!=locked['model_sha256']:raise ValueError('Changed locked model')
    if sha(source)!=locked['source_raw_sha256']:raise ValueError('Changed historical source')
    reserve_once(output)
    raw=pd.read_csv(source,low_memory=False)
    if not pd.to_numeric(raw.season_source).isin(r.PROTOCOL['seasons']).all():raise ValueError('Unapproved historical seasons')
    start,end=map(pd.Timestamp,r.PROTOCOL['retrospective_holdout']);raw.date_match=pd.to_datetime(raw.date_match)
    raw=raw[raw.date_match<end].copy()
    validate_player_games(raw)
    if not raw.game_type.eq(2).all() or not final_mask(raw).all():raise ValueError('Invalid final regular-season universe')
    frame=build_feature_frame(raw).merge(raw[['id_match','id_joueur','game_type']],on=['id_match','id_joueur'],validate='one_to_one')
    if len(frame)!=len(raw):raise ValueError('Silent row filtering')
    frame=r.augment_research_features(augment_goal_features(frame));frame['a_marque_un_but']=goal_labels(frame)
    test=frame[(frame.date_match>=start)&(frame.date_match<end)].copy()
    if test.empty:raise ValueError('Empty reserved block')
    models=joblib.load(output/'locked_models.joblib');predictions={};summaries={}
    for name in dict.fromkeys(['baseline',locked['candidate']]):
        model,cal,meta=models[name]
        if pd.Timestamp(meta['calibration_end'])>=start:raise ValueError('Calibration overlaps reserved block')
        rows=test[['date_match','id_match','id_joueur','game_type','a_marque_un_but']].copy();rows['fold']=0
        rows['probability']=cal.predict(model.predict_proba(numeric_features(test,meta['kept']))[:,1])
        predictions[name]=rows;summaries[name]=r.summary(rows)
    benchmark=next(iter(predictions.values())).copy()
    benchmark['probability']=(test.season_goal_hits_before_match.to_numpy()+10*locked['training_prevalence'])/(test.season_games_before_match.to_numpy()+10)
    predictions['player_smoothed_baseline']=benchmark;summaries['player_smoothed_baseline']=r.summary(benchmark)
    candidate=predictions[locked['candidate']]
    comparisons={name:paired_comparison(predictions[name],candidate,family_size=1) for name in ['baseline','player_smoothed_baseline']}
    for name,rows in predictions.items():rows.to_csv(output/f'holdout_{name}.csv.gz',index=False)
    result=dict(status='closed',candidate=locked['candidate'],production_approved=False,holdout_consumed=True,
        rows=len(test),games=test.id_match.nunique(),players=test.id_joueur.nunique(),dates=test.date_match.nunique(),
        start=str(test.date_match.min()),end=str(test.date_match.max()),metrics=summaries,comparisons=comparisons,
        limitation='Historical retrospective block; confirmation prospective still required. No post-holdout tuning.',
        manifest=manifest([source,output/'candidate_locked.json',Path(__file__)],GOAL_PARAMS))
    save(output/'final_result.json',result)
    print(json.dumps({k:result[k] for k in ['status','candidate','rows','games','players','dates','comparisons']},indent=2))
    return result

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--phase',choices=['lock','evaluate'],required=True);p.add_argument('--features',type=Path);p.add_argument('--development',type=Path);p.add_argument('--source',type=Path);p.add_argument('--output',type=Path,required=True);a=p.parse_args()
    if a.phase=='lock':lock(a.features,a.development,a.output)
    else:evaluate(a.source,a.output)
